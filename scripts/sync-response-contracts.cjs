// One derived response registry; operation-specific schemas remain authoritative.
const fs = require("node:fs"),
  path = require("node:path");
const root = path.resolve(__dirname, ".."),
  base = path.resolve(root, "../..");
const sources = [
  ["d3b", "开发交接/D3-最小首次交易/契约/C-D3-B接口.openapi.json"],
  ["d3a", "开发交接/D3-最小首次交易/契约/C-D3-A接口.openapi.json"],
  ["d1", "开发交接/D1-最小框架/契约/C-D1基础接口.openapi.json"],
  ["a", "开发交接/D2-准入与道具可租/契约/C-D2-A用户账号与认证.openapi.json"],
  [
    "b",
    "开发交接/D2-准入与道具可租/契约/C-D2-B工厂准入与资料管理.openapi.json",
  ],
  ["c", "开发交接/D2-准入与道具可租/契约/C-D2-C道具与库存.openapi.json"],
  ["d4", "代码/mujian-backend/src/main/resources/contracts/d4.openapi.json"],
  ["d5", "代码/mujian-backend/src/main/resources/contracts/d5.openapi.json"],
  ["d7", "开发交接/D7-运营与发布/契约/C-D7运营接口.openapi.json"],
  ["d6", "开发交接/D6-定制闭环/契约/C-D6定制接口.openapi.json"],
];
// D6 正式接管的既有 04 操作，路径、方法及 operationId 必须同时匹配。
const sharedD6Operations = new Set([
  "tradingOperation", "adminTradingOperation", "adminPayment", "adminRefunds",
  "adminRefund", "myRefund", "factorySettlementItems", "adminSettlementItems",
]);
const registered = new Map();
const out = { paths: {}, components: { schemas: {} } };
function write(file, value) {
  if (process.argv.includes("--mini-only") && file !== path.join(root, "miniprogram/services/response-contract-data.js")) return;
  const text =
    typeof value === "string" ? value : JSON.stringify(value, null, 2) + "\n";
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(file, "utf8") !== text)
      throw Error("Contract differs: " + file);
  } else fs.writeFileSync(file, text);
}
for (const [prefix, file] of sources) {
  const raw = JSON.parse(fs.readFileSync(path.join(base, file), "utf8"));
  for (const [route, operations] of Object.entries(raw.paths)) {
    for (const [method, op] of Object.entries(operations)) {
      const key = method + " " + route;
      if (prefix === "d7" && registered.has(key) && key !== "post /api/admin/auth/login") throw Error("D7 operation conflicts: " + key);
      if (prefix === "d6") {
        const previous = registered.get(key);
        if (sharedD6Operations.has(op.operationId) ? previous !== op.operationId : previous !== undefined)
          throw Error("D6 operation conflicts with existing contract: " + key);
      }
      registered.set(key, op.operationId);
    }
  }
  if (prefix === "d6" || prefix === "d7") {
    write(path.join(root, `../mujian-backend/src/main/resources/contracts/${prefix}.openapi.json`),
      fs.readFileSync(path.join(base, file), "utf8"));
  }
  if (prefix === "d4" || prefix === "d5" || prefix === "d6" || prefix === "d7") {
    const paths = Object.fromEntries(Object.entries(raw.paths).filter(([p]) => p.startsWith("/api/admin/")));
    const schemas = {};
    function collect(node) {
      if (!node || typeof node !== "object") return;
      if (node.$ref && node.$ref.startsWith("#/components/schemas/")) {
        const name = node.$ref.split("/").pop();
        if (!(name in schemas)) {
          schemas[name] = raw.components.schemas[name];
          collect(schemas[name]);
        }
      }
      Object.values(node).forEach(collect);
    }
    collect(paths);
    write(path.join(root, `admin-web/src/api/${prefix}.contract.json`), { components: { schemas }, paths });
  }
  if (prefix === "d3b") {
    write(path.join(root,"admin-web/src/api/d3b.contract.json"), {components:raw.components, paths:raw.paths});
  }
  if (prefix === "c") {
    write(
      path.join(
        root,
        "../mujian-backend/src/main/resources/contracts/d2c.openapi.json",
      ),
      raw,
    );
    write(path.join(root, "admin-web/src/api/d2c.contract.json"), {
      components: raw.components,
      paths: raw.paths,
    });
  }
  if (prefix === "b") {
    write(path.join(root, "admin-web/src/api/d2b.contract.json"), {
      components: raw.components,
      paths: raw.paths,
    });
    write(
      path.join(
        root,
        "../mujian-backend/src/main/resources/contracts/d2b.openapi.json",
      ),
      raw,
    );
    const paths = {};
    for (const [p, ops] of Object.entries(raw.paths))
      if (!p.startsWith("/api/admin/") && !p.startsWith("/api/wechat-pay/")) {
        paths[p] = {};
        for (const [m, op] of Object.entries(ops))
          paths[p][m] = op.responses["200"].content["application/json"].schema;
      }
    write(
      path.join(root, "miniprogram/services/factory-contract-data.js"),
      "// Generated by scripts/sync-response-contracts.cjs; do not edit.\nmodule.exports = " +
        JSON.stringify({ components: raw.components, paths }) +
        ";\n",
    );
  }
  const n = JSON.parse(
    JSON.stringify(raw).replaceAll(
      "#/components/schemas/",
      "#/components/schemas/" + prefix + "_",
    ),
  );
  for (const [p, ops] of Object.entries(n.paths))
    if (!p.startsWith("/api/admin/") && !p.startsWith("/api/wechat-pay/")) {
      out.paths[p] ||= {};
      for (const [m, op] of Object.entries(ops))
        out.paths[p][m] = Object.fromEntries(
          Object.entries(op.responses).map(([s, r]) => [
            s,
            r.content?.["application/json"]?.schema || {
              type: "string",
              format: "binary",
            },
          ]),
        );
    }
  for (const [k, v] of Object.entries(n.components.schemas))
    out.components.schemas[prefix + "_" + k] = v;
}
// Keep only transitively referenced schemas to avoid shipping unrelated admin types.
const used = new Set();
function refs(v) {
  if (!v || typeof v !== "object") return;
  if (v.$ref) {
    const key = v.$ref.split("/").pop();
    if (!used.has(key)) {
      used.add(key);
      refs(out.components.schemas[key]);
    }
  }
  for (const [k, x] of Object.entries(v)) if (k !== "$ref") refs(x);
}
refs(out.paths);
for (const key of Object.keys(out.components.schemas))
  if (!used.has(key)) delete out.components.schemas[key];
write(
  path.join(root, "miniprogram/services/response-contract-data.js"),
  "// Generated by scripts/sync-response-contracts.cjs; do not edit.\nmodule.exports = " +
    JSON.stringify(out) +
    ";\n",
);
console.log("Response contract copies synchronized; mini schemas:", used.size);
