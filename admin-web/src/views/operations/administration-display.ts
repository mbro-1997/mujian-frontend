export function displayCell(row: Row, key: string): string {
  if (key === "target") return [row.targetType, row.targetId].filter(Boolean).join(" · ");
  if (key === "title" && row.source)
    return [row.title, stateText[row.source.sourceType] || row.source.sourceType, row.source.sourceId]
      .filter(Boolean)
      .join(" · ");
  if (key === "enabled") return row.enabled ? "启用" : "停用";
  if (key === "identityEnabled") return row.identityEnabled ? "有效" : "停用";
  if (key === "deadlineAt" && !row[key]) return "未设置";
  if (!(key in row)) return key === "reason" ? "详见详情" : "未提供";
  return stateText[String(row[key])] || format(row[key]);
}

export const names = (row: Row) => Object.keys(labels).filter((key) => key in row && key !== "password");

function format(value: unknown): string {
  if (value == null) return "—";
  if (Array.isArray(value)) return value.map(format).join("；") || "无";
  if (typeof value === "boolean") return value ? "是" : "否";
  if (typeof value === "object") {
    return Object.entries(value)
      .map(([key, item]) => (labels[key] || key) + " " + format(item))
      .join(" · ");
  }
  return String(value);
}
